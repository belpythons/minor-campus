/** @type {import('next').NextConfig} */

// Supabase Storage serves the uploaded certificates and activity photos.
// Deriving the host from the env var keeps this correct across projects and
// avoids a wildcard that would let next/image proxy arbitrary origins.
const supabaseHost = (() => {
  try {
    return new URL(process.env.NEXT_PUBLIC_SUPABASE_URL ?? "").hostname;
  } catch {
    return null;
  }
})();

const nextConfig = {
  reactStrictMode: true,

  images: {
    remotePatterns: supabaseHost
      ? [{ protocol: "https", hostname: supabaseHost, pathname: "/storage/v1/object/public/**" }]
      : [],
  },

  // The service worker and manifest must never be cached by an intermediary,
  // otherwise a shipped fix can sit behind a stale worker for days.
  async headers() {
    return [
      {
        source: "/sw.js",
        headers: [
          { key: "Cache-Control", value: "no-cache, no-store, must-revalidate" },
          { key: "Service-Worker-Allowed", value: "/" },
        ],
      },
      {
        source: "/manifest.webmanifest",
        headers: [{ key: "Cache-Control", value: "public, max-age=0, must-revalidate" }],
      },
    ];
  },
};

export default nextConfig;
